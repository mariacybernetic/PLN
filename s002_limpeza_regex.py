"""### Por que essas decisões?
- **Blocos e linhas de boilerplate:** são elementos de interface do site, não conteúdo jornalístico.
- **Aspas e apóstrofos curvos → retos:** `don’t` e `don't` são a mesma palavra, mas seriam tokens diferentes.
- **Datas → `<DATE>`:** datas isoladas raramente carregam enquadramento, e transformá-las em um token único evita milhares de features raras.
- **Exceção: `October 7`:** é o nome de um evento e o próprio uso desse termo é relevante para *framing*. Por isso ele é preservado e padronizado.
- **Números como "73,470" foram mantidos** (contagens de mortos aparecem em vários textos e podem ser analisadas depois).

## 4. Aplicando a limpeza ao corpus
"""

contadores = {}
df_meta["texto_limpo"] = df_meta["texto"].apply(lambda t: limpar_texto(t, contadores))

