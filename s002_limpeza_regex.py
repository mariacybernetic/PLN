"""## 3. Regras de limpeza (uma por vez, com contagem)"""

# Cada regra: (nome, regex, substituição, flags)
# A ORDEM importa: primeiro blocos e linhas inteiras, depois caracteres.
M = r"(?:Jan(?:uary|\.)?|Feb(?:ruary|\.)?|Mar(?:ch|\.)?|Apr(?:il|\.)?|May|June?|July?|Aug(?:ust|\.)?|Sept?(?:ember|\.)?|Oct(?:ober|\.)?|Nov(?:ember|\.)?|Dec(?:ember|\.)?)"

REGRAS = [
    # 1) Erros de tradução: remove a marcação e mantém o resto do texto
    ("erro de tradução", r"\[ERRO DE TRADUCAO[^\]]*\]", " ", re.I),

    # 2) Boilerplate (linhas inteiras)
    ("bloco Recommended Stories",
     r"^Recommended Stories\s*\n(?:list of \d+ items\s*\n)?(?:- list \d+ of \d+.*(?:\n|$))+", "", re.M),
    ("chamada CLICK HERE",   r"^\s*CLICK HERE\b.*$", "", re.M),
    ("rótulo NewsFeed",      r"^\s*NewsFeed\s*$", "", re.M),
    ("Published On",         r"^\s*Published On\b.*$", "", re.M),
    ("crédito 'contributed'", r"^.*\bcontributed to this report\.?\s*$", "", re.M),
    ("aviso de opinião",     r"^The views expressed in this article\b.*$", "", re.M),

    # 3) URLs e menções
    ("URLs",      r"https?://\S+|www\.\S+", " ", 0),
    ("@menções",  r"(?<!\w)@\w+", " ", 0),

    # 4) Pontuação e aspas
    ("aspas duplas curvas",   r"[“”„]", '"', 0),
    ("apóstrofos/aspas simples curvas", r"[‘’`´]", "'", 0),
    ("travessões",            r"[–—]", " - ", 0),
    ("reticências",           r"…", "...", 0),

    # 5) Datas
    # 'October 7' nomeia um evento (ataque de 7/10/2023), então é PROTEGIDO e padronizado
    ("proteger 'October 7'",  r"\bOct(?:ober|\.)?\s+7(?:,\s*2023)?\b", "OCTOBER7EVENT", 0),
    ("data dia-mês-ano",      r"\b\d{1,2}\s+" + M + r"\s+\d{4}\b", "<DATE>", 0),
    ("data mês dia, ano",     r"\b" + M + r"\s+\d{1,2}(?:,\s*\d{4})\b", "<DATE>", 0),
    ("data mês ano",          r"\b" + M + r"\s+\d{4}\b", "<DATE>", 0),
    ("data mês dia",          r"\b" + M + r"\s+\d{1,2}\b", "<DATE>", 0),
    ("data numérica",         r"\b\d{4}-\d{2}-\d{2}\b|\b\d{1,2}/\d{1,2}/\d{2,4}\b", "<DATE>", 0),
    ("restaurar 'October 7'", r"OCTOBER7EVENT", "October 7", 0),

    # 6) Espaços
    ("espaços repetidos",  r"[ \t\u00a0]+", " ", 0),
    ("espaço antes de quebra", r" *\n *", "\n", 0),
    ("linhas em branco",   r"\n{2,}", "\n", 0),
]

def limpar_texto(texto, contador=None):
    for nome, padrao, repl, flags in REGRAS:
        texto, n = re.subn(padrao, repl, texto, flags=flags)
        if contador is not None:
            contador[nome] = contador.get(nome, 0) + n
    return texto.strip()

