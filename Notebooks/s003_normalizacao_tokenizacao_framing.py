"""## 4. Tokenização com spaCy

Usamos `nlp.pipe` para processar todos os artigos de uma vez (mais rápido que rodar `nlp()` um por
um). Para cada artigo, guardamos:

- `tokens`: tokens alfabéticos, caixa original preservada (para entidades/POS no Notebook 04);
- `tokens_lower`: os mesmos tokens em minúsculas (para frequência/comparação bruta entre veículos);
- `num_tokens`: contagem de tokens, útil para checar artigos anormalmente curtos/longos.

Pontuação, números isolados e espaços são descartados

"""

def tokenizar(doc):
    tokens = [tok.text for tok in doc if tok.is_alpha]
    return tokens


textos = df["texto_normalizado"].tolist()
todos_tokens = []

for doc in nlp.pipe(textos, batch_size=32, disable=["parser", "ner"]):
    todos_tokens.append(tokenizar(doc))

df["tokens"] = todos_tokens
df["tokens_lower"] = df["tokens"].apply(lambda lista: [t.lower() for t in lista])
df["num_tokens"] = df["tokens"].apply(len)

df[["id", "veiculo", "grupo", "num_tokens"]].head(10)

