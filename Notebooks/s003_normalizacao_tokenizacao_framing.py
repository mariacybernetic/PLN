"""## 3. Normalização adicional

Antes de tokenizar, resolvemos alguns resíduos comuns em texto traduzido automaticamente e extraído
da web: aspas curvas, travessões duplicados, espaços múltiplos, e qualquer marcador de erro de
tradução que possa ter sobrado (`[ERRO DE TRADUCAO: ...]`) do Notebook 01.

"""

def normalizar_texto(texto):
    texto = re.sub(r"\[ERRO DE TRADUCAO:.*?\]", " ", texto)          # remove marcadores de erro
    texto = texto.replace("\u201c", '"').replace("\u201d", '"')       # aspas curvas -> retas
    texto = texto.replace("\u2018", "'").replace("\u2019", "'")
    texto = re.sub(r"[\u2013\u2014]+", "-", texto)                    # travessões -> hífen simples
    texto = re.sub(r"\s+", " ", texto).strip()                        # espaços múltiplos
    return texto


df["texto_normalizado"] = df["texto_limpo"].apply(normalizar_texto)

